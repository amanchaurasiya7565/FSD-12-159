// waf to take any digit (0-9) and return its in word as like 0 -one ,5-five .
const toWord = (digit) => {
    const words = ["Zero", "One", "two", "three", "Four", "five", "six", "sevem", "Eight", "Nine"];
    return words[digit];
}
console.log(toWord(5));
